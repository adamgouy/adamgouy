"""Tests for the OOP exercises. Run from the repository root with: python -m pytest"""
import pytest

from inheritance import (
    BankAccount, Bicycle, Car, Employee, InsufficientFundsError, Person as BasePerson,
    SavingsAccount, Student, Vehicle,
)
from operator_overloading import Circle, Complex, Matrix, Person, Point, Vector


# ---------- operator overloading ----------

def test_complex_addition_and_subtraction():
    assert Complex(2, 3) + Complex(1, -4) == Complex(3, -1)
    assert Complex(2, 3) - Complex(1, -4) == Complex(1, 7)
    assert str(Complex(3, -1)) == "3 - 1i"


def test_complex_compared_to_another_type_is_not_equal():
    assert Complex(1, 0) != "1"


def test_person_compared_by_age():
    assert Person("Sara", 28, "F") > Person("Tom", 20, "M")
    assert not Person("Sara", 28, "F") > Person("Tom", 34, "M")


def test_vector_dot_product():
    assert Vector(1, 0, 2) * Vector(3, 5, 4) == 11


def test_circle_all_comparisons():
    small, big = Circle(1), Circle(2)
    assert small < big and small <= big and big > small and big >= small
    assert small == Circle(1) and small != big


def test_circle_rejects_negative_radius():
    with pytest.raises(ValueError):
        Circle(-1)


def test_points_are_compared_by_distance_to_origin():
    assert Point(3, 4) == Point(0, 5)          # both at distance 5
    assert Point(1, 1) < Point(3, 4)
    assert Point(6, 8) >= Point(3, 4)          # generated by @total_ordering
    assert sorted([Point(6, 8), Point(0, 1)]) == [Point(0, 1), Point(6, 8)]


def test_matrix_product():
    a = Matrix([[1, 2, 3], [4, 5, 6]])
    b = Matrix([[7, 8], [9, 10], [11, 12]])
    assert a * b == Matrix([[58, 64], [139, 154]])


def test_matrix_product_with_wrong_dimensions():
    with pytest.raises(ValueError):
        Matrix([[1, 2]]) * Matrix([[1, 2]])


def test_matrix_rows_must_have_the_same_length():
    with pytest.raises(ValueError):
        Matrix([[1, 2], [3]])


# ---------- inheritance ----------

def test_each_vehicle_overrides_drive():
    messages = [v.drive() for v in (Vehicle(), Car("Peugeot"), Bicycle("Decathlon"))]
    assert len(set(messages)) == 3
    assert "car" in messages[1] and "bicycle" in messages[2]


def test_student_and_employee_reuse_the_parent_introduction():
    student = Student("Yanis", 19, "Paris", "Sorbonne University", "mathematics")
    employee = Employee("Claire", 31, "Bordeaux", "Airbus", "data analyst")
    base = BasePerson("Yanis", 19, "Paris").introduce()
    assert student.introduce().startswith(base)
    assert "Sorbonne University" in student.introduce()
    assert "Airbus" in employee.introduce()
    assert isinstance(student, BasePerson) and isinstance(employee, BasePerson)


def test_deposit_and_withdraw():
    account = BankAccount("Lina", 100)
    account.deposit(50)
    account.withdraw(30)
    assert account.check_balance() == 120


@pytest.mark.parametrize("amount", [0, -10])
def test_amounts_must_be_positive(amount):
    with pytest.raises(ValueError):
        BankAccount("Lina", 100).deposit(amount)


def test_transfer_moves_money_between_accounts():
    current, savings = BankAccount("Lina", 300), SavingsAccount("Lina", 1000)
    current.transfer(200, savings)
    assert current.balance == 100 and savings.balance == 1200


def test_failed_transfer_changes_nothing():
    current, savings = BankAccount("Lina", 50), SavingsAccount("Lina", 1000)
    with pytest.raises(InsufficientFundsError):
        current.transfer(200, savings)
    assert current.balance == 50 and savings.balance == 1000


def test_savings_account_adds_interest():
    savings = SavingsAccount("Lina", 2000, interest_rate=0.03)
    assert savings.add_interest() == 60
    assert savings.check_balance() == 2060
    assert isinstance(savings, BankAccount)
